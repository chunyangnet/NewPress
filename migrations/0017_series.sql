CREATE TABLE np_series (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('topic','series')),
    status text NOT NULL CHECK (status IN ('draft','publish')),
    title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    slug text NOT NULL UNIQUE,
    description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 2000),
    cover_url text NOT NULL DEFAULT '',
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX np_series_public ON np_series(id DESC) WHERE status='publish';
CREATE TABLE np_series_posts (
    series_id bigint NOT NULL REFERENCES np_series(id) ON DELETE CASCADE,
    post_id bigint NOT NULL REFERENCES np_posts(id) ON DELETE RESTRICT,
    position integer NOT NULL CHECK (position BETWEEN 0 AND 199),
    PRIMARY KEY (series_id, post_id),
    UNIQUE (series_id, position)
);
CREATE INDEX np_series_posts_post ON np_series_posts(post_id,series_id);
