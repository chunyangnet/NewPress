CREATE TABLE np_content_redirects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path text NOT NULL UNIQUE CHECK (octet_length(path) BETWEEN 2 AND 2048),
    post_id bigint NOT NULL REFERENCES np_posts(id) ON DELETE CASCADE,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    automatic boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX np_content_redirects_post ON np_content_redirects(post_id);
