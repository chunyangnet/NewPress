// Post is the canonical content record shared by the public theme, the admin
// application and repository implementations. Version is incremented on every
// write and is required for optimistic concurrency control.
type Post struct {
	ID            int64          `json:"id"`
	AuthorID      int64          `json:"author_id"`
	Type          string         `json:"type"`
	Status        string         `json:"status"`
	Slug          string         `json:"slug"`
	Title         string         `json:"title"`
	Excerpt       string         `json:"excerpt"`
	ContentSource string         `json:"content_source,omitempty"`
	ContentHTML   string         `json:"content_html,omitempty"`
	CoverURL      string         `json:"cover_url,omitempty"`
	AuthorName    string         `json:"author_name"`
	Category      string         `json:"category"`
	Categories    []Term         `json:"categories,omitempty"`
	Tags          []Term         `json:"tags,omitempty"`
	CommentStatus string         `json:"comment_status"`
	PublishedAt   time.Time      `json:"published_at"`
	CreatedAt     time.Time      `json:"created_at"`
	UpdatedAt     time.Time      `json:"updated_at"`
	Version       int64          `json:"version"`
	Meta          map[string]any `json:"meta,omitempty"`
}

// PostInput contains all fields that may be changed through the content editor.
// ContentHTML is generated by NormalizePostInput and must never be accepted
// directly from an HTTP request.
type PostInput struct {
	Resources *resources.Config `json:",omitempty"`
	// Nil preserves the canonical pin state in a partial update.
	Pinned       *bool         `json:",omitempty"`
	ArticleBadge *ArticleBadge `json:",omitempty"`
	Flash        *FlashFields  `json:",omitempty"`
	// Empty fields preserve existing plugin metadata on ordinary edits.
	AIPolicy      string `json:",omitempty"`
	AITopics      string `json:",omitempty"`
	AuthorID      int64
	Type          string
	Status        string
	Slug          string
	Title         string
	Excerpt       string
	ContentSource string
	ContentHTML   string
	CoverURL      string
	AuthorName    string
	Category      string
	CategoryIDs   []int64
	TagNames      []string
	CommentStatus string
	PublishedAt   time.Time
	Actor         string
}

type Mutation struct {
	ExpectedVersion int64
	Actor           string
}

// BulkMutation identifies one exact canonical version participating in an
// atomic batch. IDs and versions are intentionally paired so callers cannot
// accidentally zip two independently ordered form fields.
type BulkMutation struct {
	ID              int64
	ExpectedVersion int64
}

// BulkStatusChange is an all-or-nothing content status transition. Repository
// implementations must validate every item before changing any item, clear
// all affected autosaves and append one revision for every changed post in the
// same lock or database transaction.
type BulkStatusChange struct {
	// Delete permanently removes trashed posts instead of recording a transition.
	Delete   bool
	Items    []BulkMutation
	Status   string
	Actor    string
	AuthorID int64
}

type AdminQuery struct {
	// Internal scheduling window: (PublishedAfter, PublishedBefore], before pagination.
	PublishedAfter       time.Time
	PublishedBefore      time.Time
	PublicationAscending bool
	AuthorID             int64
	Type                 string
	Status               string
	Search               string
	Limit                int
	Offset               int
}

type AdminList struct {
	Items        []Post         `json:"items"`
	Total        int            `json:"total"`
	StatusCounts map[string]int `json:"status_counts"`
	TypeCounts   map[string]int `json:"type_counts"`
}

// PublishedPage contains visible posts with pinned articles first, then by
// publication time and ID, newest first, and the total visible count.
type PublishedPage struct {
	Items []Post
	Total int
}

type Revision struct {
	ID        int64     `json:"id"`
	PostID    int64     `json:"post_id"`
	Version   int64     `json:"version"`
	Snapshot  Post      `json:"snapshot"`
	Actor     string    `json:"actor"`
	CreatedAt time.Time `json:"created_at"`
}

// Autosave is an identity-scoped recovery snapshot. It deliberately lives
// outside the canonical post version and revision stream: saving an autosave
// must never publish content, advance Post.Version, or change Post.UpdatedAt.
type Autosave struct {
	PostID        int64     `json:"post_id"`
	OwnerKey      string    `json:"owner_key"`
	SourceVersion int64     `json:"source_version"`
	Snapshot      Post      `json:"snapshot"`
	UpdatedAt     time.Time `json:"updated_at"`
	ExpiresAt     time.Time `json:"expires_at"`
}

