type ValidationError struct {
	Fields map[string]string
}

func (err *ValidationError) Error() string {
	return "content validation failed"
}

func FieldErrors(err error) map[string]string {
	var validation *ValidationError
	if errors.As(err, &validation) {
		return cloneStringMap(validation.Fields)
	}
	return nil
}

func NormalizePostInput(input PostInput, now time.Time) (PostInput, map[string]string) {
	if now.IsZero() {
		now = time.Now()
	}
	fields := make(map[string]string)
	if input.Resources != nil {
		normalized, err := resources.Normalize(*input.Resources)
		if err != nil {
			fields["resources"] = "资源配置无效，请检查条件、地址、答题与表单设置"
		} else {
			input.Resources = &normalized
		}
	}
	if input.ArticleBadge != nil {
		badge, badgeFields := NormalizeArticleBadge(*input.ArticleBadge)
		input.ArticleBadge = &badge
		for key, value := range badgeFields {
			fields[key] = value
		}
	}
	if !validateUTF8Fields(fields, map[string]string{
		"type": input.Type, "status": input.Status, "slug": input.Slug,
		"title": input.Title, "excerpt": input.Excerpt, "content_source": input.ContentSource,
		"cover_url": input.CoverURL, "category": input.Category, "comment_status": input.CommentStatus,
		"author_name": input.AuthorName, "actor": input.Actor, "ai_pro_max": input.AIPolicy, "ai_topics": input.AITopics,
	}) {
		return input, fields
	}
	if input.AuthorID < 0 {
		fields["author_id"] = "作者编号不正确"
	}
	if input.AIPolicy != "" && input.AIPolicy != "inherit" && input.AIPolicy != "on" && input.AIPolicy != "off" {
		fields["ai_pro_max"] = "自动化开关值无效"
	}
	if len(input.AITopics) > 64<<10 {
		fields["ai_topics"] = "话题内容过长"
	}
	input.Type = strings.ToLower(strings.TrimSpace(input.Type))
	if input.Type == "" {
		input.Type = TypePost
	}
	if !ValidType(input.Type) {
		fields["type"] = "内容类型必须是文章或页面"
	}

	input.Status = strings.ToLower(strings.TrimSpace(input.Status))
	if input.Status == "" {
		input.Status = StatusDraft
	}
	if !ValidStatus(input.Status) {
		fields["status"] = "内容状态不受支持"
	}

	input.Title = strings.TrimSpace(input.Title)
	if input.Title == "" {
		fields["title"] = "标题不能为空"
	} else if utf8.RuneCountInString(input.Title) > MaxTitleRunes {
		fields["title"] = fmt.Sprintf("标题不能超过 %d 个字符", MaxTitleRunes)
	} else if containsControl(input.Title) {
		fields["title"] = "标题不能包含控制字符"
	}

	input.Slug = NormalizeSlug(input.Slug)
	if input.Slug == "" {
		input.Slug = NormalizeSlug(input.Title)
	}
	if input.Slug == "" {
		prefix := input.Type
		if !ValidType(prefix) {
			prefix = TypePost
		}
		// Titles without ASCII letters or digits share the timestamp fallback.
		// Keep normalization deterministic while separating different titles
		// created in the same second, including Chinese titles and emoji.
		titleHash := sha256.Sum256([]byte(input.Title))
		input.Slug = fmt.Sprintf("%s-%s-%x", prefix, now.Format("20060102-150405"), titleHash[:8])
	}
	if !ValidSlug(input.Slug) {
		fields["slug"] = "别名只能包含小写字母、数字和连字符，且不能超过 128 字节"
	}

	input.Excerpt = strings.TrimSpace(input.Excerpt)
	if utf8.RuneCountInString(input.Excerpt) > MaxExcerptRunes {
		fields["excerpt"] = fmt.Sprintf("摘要不能超过 %d 个字符", MaxExcerptRunes)
	} else if containsControlExceptWhitespace(input.Excerpt) {
		fields["excerpt"] = "摘要不能包含控制字符"
	}

	input.ContentSource = strings.TrimSpace(input.ContentSource)
	if len(input.ContentSource) > MaxContentBytes {
		fields["content_source"] = "正文不能超过 2 MiB"
	} else {
		input.ContentHTML = sanitizeContent(input.ContentSource)
	}
	if input.Excerpt == "" {
		input.Excerpt = generatedExcerpt(input.ContentHTML)
	}

	input.CoverURL = strings.TrimSpace(input.CoverURL)
	if err := validateCoverURL(input.CoverURL); err != nil {
		fields["cover_url"] = err.Error()
	}

	input.Category = strings.TrimSpace(input.Category)
	if input.Category == "" && input.Type == TypePost && len(input.CategoryIDs) == 0 {
		input.Category = "未分类"
	}
	if utf8.RuneCountInString(input.Category) > MaxCategoryRunes || containsControl(input.Category) {
		fields["category"] = fmt.Sprintf("栏目名称不能超过 %d 个字符或包含控制字符", MaxCategoryRunes)
	}
	var categoryIDsValid bool
	input.CategoryIDs, categoryIDsValid = normalizePositiveIDs(input.CategoryIDs)
	if !categoryIDsValid {
		fields["category_ids"] = "分类编号必须是互不重复的正整数"
	}
	if len(input.CategoryIDs) > MaxCategoriesPerPost {
		fields["category_ids"] = fmt.Sprintf("每篇文章最多选择 %d 个分类", MaxCategoriesPerPost)
	}
	normalizedTags, tagErr := NormalizeTagNames(input.TagNames)
	input.TagNames = normalizedTags
	if tagErr != nil {
		fields["tags"] = tagErr.Error()
	}
	if input.Type == TypePage {
		input.Category = ""
		input.CategoryIDs = nil
		input.TagNames = nil
	}

	input.CommentStatus = strings.ToLower(strings.TrimSpace(input.CommentStatus))
	if input.CommentStatus == "" {
		input.CommentStatus = CommentOpen
	}
	if input.CommentStatus != CommentOpen && input.CommentStatus != CommentClosed {
		fields["comment_status"] = "评论状态必须是开启或关闭"
	}

	input.AuthorName = strings.TrimSpace(input.AuthorName)
	if input.AuthorName == "" {
		input.AuthorName = "NewPress"
	}
	if utf8.RuneCountInString(input.AuthorName) > 160 || containsControl(input.AuthorName) {
		fields["author_name"] = "作者名称不能超过 160 个字符或包含控制字符"
	}
	input.Actor = strings.TrimSpace(input.Actor)
	if input.Actor == "" {
		input.Actor = input.AuthorName
	}

	// A publish request with a future timestamp becomes a scheduled item. A
	// scheduled timestamp that is already due becomes immediately publishable.
	switch input.Status {
	case StatusPublish:
		if input.PublishedAt.IsZero() {
			input.PublishedAt = now
		} else if input.PublishedAt.After(now) {
			input.Status = StatusFuture
		}
	case StatusFuture:
		if input.PublishedAt.IsZero() {
			fields["published_at"] = "定时发布必须选择发布时间"
		} else if !input.PublishedAt.After(now) {
			input.Status = StatusPublish
		}
	case StatusPrivate:
		if input.PublishedAt.IsZero() {
			input.PublishedAt = now
		}
	}
	if !input.PublishedAt.IsZero() && input.PublishedAt.After(now.AddDate(10, 0, 0)) {
		fields["published_at"] = "发布时间不能超过未来 10 年"
	}

	normalizeFlash(&input, fields)
	return input, fields
}

func ValidType(value string) bool {
	return value == TypePost || value == TypePage || value == TypeFlash
}

func ValidStatus(value string) bool {
	switch value {
	case StatusDraft, StatusPending, StatusPublish, StatusFuture, StatusPrivate, StatusTrash:
		return true
	default:
		return false
	}
}

func ValidSlug(value string) bool {
	if len(value) < 1 || len(value) > MaxSlugBytes {
		return false
	}
	if value[0] == '-' || value[len(value)-1] == '-' || strings.Contains(value, "--") {
		return false
	}
	for _, character := range value {
		if (character >= 'a' && character <= 'z') || (character >= '0' && character <= '9') || character == '-' {
			continue
		}
		return false
	}
	return true
}

func NormalizeSlug(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	var result strings.Builder
	result.Grow(min(len(value), MaxSlugBytes))
	separator := false
	for _, character := range value {
		switch {
		case character >= 'a' && character <= 'z', character >= '0' && character <= '9':
			if separator && result.Len() > 0 && result.Len() < MaxSlugBytes {
				result.WriteByte('-')
			}
			separator = false
			if result.Len() < MaxSlugBytes {
				result.WriteRune(character)
			}
		case character == '-' || character == '_' || unicode.IsSpace(character):
			separator = result.Len() > 0
		}
		if result.Len() >= MaxSlugBytes {
			break
		}
	}
	return strings.Trim(result.String(), "-")
}

func PublicAt(post Post, now time.Time) bool {
	if !ValidType(post.Type) {
		return false
	}
	if post.Status != StatusPublish && post.Status != StatusFuture {
		return false
	}
	return !post.PublishedAt.IsZero() && !post.PublishedAt.After(now)
}

func NormalizeAdminQuery(query AdminQuery) (AdminQuery, error) {
	if query.AuthorID < 0 {
		return AdminQuery{}, fmt.Errorf("invalid author ID")
	}
	query.Type = strings.ToLower(strings.TrimSpace(query.Type))
	query.Status = strings.ToLower(strings.TrimSpace(query.Status))
	query.Search = strings.TrimSpace(query.Search)
	if query.Type != "" && !ValidType(query.Type) {
		return AdminQuery{}, fmt.Errorf("invalid content type")
	}
	if query.Status != "" && query.Status != "all" && !ValidStatus(query.Status) {
		return AdminQuery{}, fmt.Errorf("invalid content status")
	}
	if !utf8.ValidString(query.Search) || containsControl(query.Search) {
		return AdminQuery{}, fmt.Errorf("invalid search query")
	}
	if utf8.RuneCountInString(query.Search) > MaxAdminSearchRunes {
		return AdminQuery{}, fmt.Errorf("search query is too long")
	}
	if query.Status == "all" {
		query.Status = ""
	}
	if query.Limit <= 0 {
		query.Limit = 20
	}
	if query.Limit > 100 {
		query.Limit = 100
	}
	if query.Offset < 0 {
		query.Offset = 0
	}
	return query, nil
}

// NormalizeBulkStatusChange validates the complete mutation set and returns a
// deterministic ID-ordered copy. Sorting gives PostgreSQL implementations a
// stable row-lock order and keeps memory/PostgreSQL result ordering identical.
func NormalizeBulkStatusChange(change BulkStatusChange) (BulkStatusChange, map[string]string) {
	fields := make(map[string]string)
	change.Status = strings.ToLower(strings.TrimSpace(change.Status))
	change.Actor = strings.TrimSpace(change.Actor)
	if !ValidStatus(change.Status) {
		fields["status"] = "内容状态不受支持"
	}
	if change.Delete && change.Status != StatusTrash {
		fields["status"] = "永久删除仅支持回收站内容"
	}
	if !utf8.ValidString(change.Actor) || utf8.RuneCountInString(change.Actor) > 160 || containsControl(change.Actor) {
		fields["actor"] = "操作者名称不能超过 160 个字符或包含控制字符"
	}
	if change.AuthorID < 0 {
		fields["author_id"] = "作者范围不正确"
	}
	if len(change.Items) == 0 {
		fields["selection"] = "至少选择一项内容"
	} else if len(change.Items) > MaxBulkMutations {
		fields["selection"] = fmt.Sprintf("单次最多操作 %d 项内容", MaxBulkMutations)
	}

	items := append([]BulkMutation(nil), change.Items...)
	sort.Slice(items, func(left, right int) bool { return items[left].ID < items[right].ID })
	for index, item := range items {
		if item.ID <= 0 || item.ExpectedVersion <= 0 {
			fields["selection"] = "所选内容包含无效编号或版本"
			break
		}
		if index > 0 && items[index-1].ID == item.ID {
			fields["selection"] = "同一项内容不能重复选择"
			break
		}
	}
	change.Items = items
	return change, fields
}

func sanitizeContent(source string) string {
	if source == "" {
		return ""
	}
	if strings.Contains(source, "<") {
		return strings.TrimSpace(contenthtml.Sanitize(source))
	}
	paragraphs := strings.Split(strings.ReplaceAll(source, "\r\n", "\n"), "\n\n")
	var result strings.Builder
	for _, paragraph := range paragraphs {
		paragraph = strings.TrimSpace(paragraph)
		if paragraph == "" {
			continue
		}
		paragraph = html.EscapeString(paragraph)
		paragraph = strings.ReplaceAll(paragraph, "\n", "<br>")
		result.WriteString("<p>")
		result.WriteString(paragraph)
		result.WriteString("</p>")
	}
	return result.String()
}

func generatedExcerpt(contentHTML string) string {
	// The source is already sanitized. Tokenization decodes entities once and
	// keeps block boundaries without separating adjacent inline formatting.
	tokens := htmlparser.NewTokenizer(strings.NewReader(contentHTML))
	var text strings.Builder
	for token := tokens.Next(); token != htmlparser.ErrorToken; token = tokens.Next() {
		switch token {
		case htmlparser.TextToken:
			text.Write(tokens.Text())
		case htmlparser.StartTagToken, htmlparser.EndTagToken, htmlparser.SelfClosingTagToken:
			name, _ := tokens.TagName()
			switch string(name) {
			case "address", "article", "aside", "blockquote", "br", "dd", "div", "dl", "dt", "figcaption", "figure", "footer", "h1", "h2", "h3", "h4", "h5", "h6", "header", "hr", "li", "main", "nav", "ol", "p", "pre", "section", "table", "td", "th", "tr", "ul":
				text.WriteByte(' ')
			}
		}
	}
	plain := strings.Join(strings.Fields(text.String()), " ")
	runes := []rune(plain)
	if len(runes) > 180 {
		plain = strings.TrimSpace(string(runes[:180])) + "…"
	}
	return plain
}

func validateCoverURL(value string) error {
	if value == "" {
		return nil
	}
	if len(value) > MaxCoverURLBytes || containsControl(value) || strings.Contains(value, "\\") {
		return errors.New("封面地址过长或包含非法字符")
	}
	parsed, err := url.Parse(value)
	if err != nil {
		return errors.New("封面地址格式不正确")
	}
	if parsed.IsAbs() {
		return errors.New("封面仅允许站内绝对路径，外部图片请先导入媒体库")
	}
	if parsed.Host != "" || !strings.HasPrefix(parsed.Path, "/") || strings.HasPrefix(parsed.Path, "//") {
		return errors.New("站内封面必须使用以单个 / 开头的绝对路径")
	}
	for _, segment := range strings.Split(parsed.Path, "/") {
		decoded, err := url.PathUnescape(segment)
		if err != nil || decoded == ".." {
			return errors.New("封面路径不能包含目录穿越片段")
		}
	}
	if path.Clean(parsed.Path) == "." {
		return errors.New("封面路径不能为空")
	}
	return nil
}

func containsControl(value string) bool {
	for _, character := range value {
		if unicode.IsControl(character) {
			return true
		}
	}
	return false
}

func containsControlExceptWhitespace(value string) bool {
	for _, character := range value {
		if unicode.IsControl(character) && character != '\n' && character != '\r' && character != '\t' {
			return true
		}
	}
	return false
}

func cloneStringMap(source map[string]string) map[string]string {
	if len(source) == 0 {
		return nil
	}
	result := make(map[string]string, len(source))
	for key, value := range source {
		result[key] = value
	}
	return result
}
