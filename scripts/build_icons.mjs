// A pinned, local Lucide subset. Legacy IDs remain stable for saved navigation.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../third_party/lucide/icons.json', import.meta.url));

export async function buildIconSprite(target, check = false) {
  const { version, icons } = JSON.parse(await readFile(source, 'utf8'));
  // Check every explicit template reference, including hidden/conditional UI.
  // Runtime menu names are preserved by the stable aliases in the catalog.
  async function validate(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const file = resolve(directory, entry.name);
      if (entry.isDirectory()) await validate(file);
      else if (entry.name.endsWith('.html') && file !== resolve(target)) {
        const template = await readFile(file, 'utf8');
        for (const [, name] of template.matchAll(/template\s+"icon"\s+"([^"]+)"/g)) {
          if (!Object.hasOwn(icons, name)) throw new Error(`${file} references missing icon "${name}"`);
        }
      }
    }
  }
  await validate(resolve(dirname(target), '..'));
  const symbols = Object.entries(icons).map(([name, icon]) => {
    if (!/^[a-z0-9-]+$/.test(name) || !icon.body || /<(?:script|foreignObject)\b|\bon\w+=/i.test(icon.body)) {
      throw new Error(`Invalid local icon: ${name}`);
    }
    return `  <symbol id="icon-${name}" viewBox="0 0 24 24"${icon.fill ? ' fill="currentColor" stroke="none"' : ''}>${icon.body}</symbol>`;
  });
  const value = `{{/* Generated by scripts/build_icons.mjs. Lucide ${version}; ISC and Feather MIT notices in THIRD_PARTY_NOTICES.md. */}}
{{define "icon"}}<svg class="icon icon-{{.}}" viewBox="0 0 24 24" width="24" height="24" aria-hidden="true" focusable="false"><use href="#icon-{{.}}"></use></svg>{{end}}

{{define "rating-5"}}<span class="rating-stars" aria-hidden="true">{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}</span>{{end}}
{{define "rating-4"}}<span class="rating-stars" aria-hidden="true">{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}{{template "icon" "star-fill"}}{{template "icon" "star"}}</span>{{end}}

{{define "icon-sprite"}}
<svg class="icon-sprite" xmlns="http://www.w3.org/2000/svg" width="0" height="0" aria-hidden="true" focusable="false">
${symbols.join('\n')}
</svg>
{{end}}
`;
  if (check) {
    if (await readFile(target, 'utf8').catch(() => '') !== value) throw new Error(`${target} is stale; run npm run build:frontend`);
  } else await writeFile(target, value);
}
